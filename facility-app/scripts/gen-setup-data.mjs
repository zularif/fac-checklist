// Runs before every build (npm run build). Packs migrations/0001_init.sql and the
// seed files into worker/setup-data.generated.js, so the /setup page works the same
// whether the app is deployed as a Cloudflare Worker or as Cloudflare Pages.
import fs from 'node:fs'
import path from 'node:path'
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8')
const seeds = fs.readdirSync(path.join(root, 'seed')).filter((f) => /^\d\d_.*\.sql$/.test(f)).sort()
const out = `// GENERATED by scripts/gen-setup-data.mjs — do not edit. Edit migrations/ and seed/ instead.
export const schemaSql = ${JSON.stringify(read('migrations/0001_init.sql'))}
export const seedFiles = ${JSON.stringify(seeds.map((f) => ({ file: f, sql: read('seed/' + f) })))}
export const techList = ${read('seed/tech_list.json').trim()}
`
fs.writeFileSync(path.join(root, 'worker/setup-data.generated.js'), out)
console.log(`setup data: schema + ${seeds.length} seed files`)
